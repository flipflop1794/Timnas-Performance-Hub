// Generates SYNTHETIC PUBG Mobile scrim logs for demos and tests.
// Indonesia has no public per-match PUBG Mobile data, so the demo uses invented lobbies with
// a few patterns planted on purpose (so tests can check the engine finds them).
// Every output line is stamped SYNTHETIC. Never mix these files with real logs.
import { writeFileSync } from 'node:fs';
import { rng, pick } from '../src/core/stats.js';

const r = rng(2026);
const TEAMS = ['INA (demo)', ...Array.from({ length: 15 }, (_, i) => `Team ${String(i + 2).padStart(2, '0')}`)];
const MAPS = { Erangel: ['Pochinki', 'School', 'Georgopol', 'Yasnaya', 'Military Base', 'Rozhok', 'Mylta Power', 'Novorepnoye'], Miramar: ['Pecado', 'Hacienda', 'Los Leones', 'San Martin', 'El Pozo', 'Monte Nuevo', 'Chumacera', 'Prison'], Sanhok: ['Bootcamp', 'Paradise', 'Ruins', 'Pai Nan', 'Camp Alpha', 'Quarry', 'Tat Mok', 'Ha Tinh'] };
const INA_DROP = { Erangel: 'Pochinki', Miramar: 'Hacienda', Sanhok: 'Paradise' };
const m = [], f = [];
let mid = 0;
for (let day = 1; day <= 4; day++) for (let g = 1; g <= 6; g++) {
  mid++;
  const map = ['Erangel', 'Miramar', 'Sanhok'][(g - 1) % 3];
  const lobby = 1 + Math.floor(r() * 5);
  // Strength: INA mid-pack; other teams random strengths.
  const strength = TEAMS.map((t, i) => (i === 0 ? 0.55 : 0.2 + r() * 0.7) + r() * 0.6);
  const order = TEAMS.map((t, i) => i).sort((a, b) => strength[b] - strength[a]);
  const id = `S${String(mid).padStart(3, '0')}`;
  const strat = ['balanced', 'aggressive', 'passive'][Math.floor(r() * 3)];
  order.forEach((ti, idx) => {
    let placement = idx + 1;
    const t = TEAMS[ti];
    let drop = pick(r, MAPS[map]), contested = r() < 0.25 ? 1 : 0;
    let died = placement === 1 ? 0 : placement >= 13 ? 1 + Math.floor(r() * 2) : placement >= 9 ? 2 + Math.floor(r() * 2) : placement >= 5 ? 3 + Math.floor(r() * 2) : 5 + Math.floor(r() * 2);
    if (ti === 0) {
      drop = r() < 0.75 ? INA_DROP[map] : pick(r, MAPS[map]);
      contested = drop === 'Pochinki' ? (r() < 0.65 ? 1 : 0) : (r() < 0.3 ? 1 : 0);
      // Planted: contested Pochinki often ends in zone 1; reaching zone 3 often ends in zone 3-4.
      if (drop === 'Pochinki' && contested && r() < 0.55) { died = 1; placement = 0; }
      else if (died >= 5 && r() < 0.5) { died = 3 + Math.floor(r() * 2); placement = 0; }
    }
    m.push({ id, day, g, map, lobby, t, placement, drop, contested, died, strat: ti === 0 ? strat : 'balanced' });
  });
  // Re-rank placements so each match has unique 1..16 respecting INA's forced exits.
  const rows = m.filter((x) => x.id === id);
  const ina = rows.find((x) => x.t === TEAMS[0]);
  if (ina.placement === 0) {
    const target = ina.died === 1 ? 13 + Math.floor(r() * 4) : 6 + Math.floor(r() * 5);
    const others = rows.filter((x) => x !== ina).sort((a, b) => a.placement - b.placement);
    others.splice(target - 1, 0, ina);
    others.forEach((x, i) => { x.placement = i + 1; });
  }
  rows.forEach((x) => {
    const surv = Math.round(x.died === 0 ? 1800 + r() * 200 : 180 + x.died * 300 + r() * 200);
    const base = x.t === TEAMS[0] ? 2.2 : 2.6;
    const elims = Math.max(0, Math.round(base + (17 - x.placement) * 0.25 + (r() - 0.5) * 3 + (x.strat === 'aggressive' ? 1.5 : x.strat === 'passive' ? -1 : 0)));
    const e1 = Math.min(elims, Math.round(elims * (0.3 + r() * 0.2))), e3 = Math.min(elims - e1, x.placement <= 4 ? Math.round(elims * 0.3) : 0);
    x.elims = elims; x.e1 = e1; x.e2 = elims - e1 - e3; x.e3 = e3; x.surv = surv;
    x.vehicle = x.t === TEAMS[0] && x.drop === 'Pochinki' ? (r() < 0.4 ? 1 : 0) : (r() < 0.75 ? 1 : 0);
    x.entry = x.t === TEAMS[0] ? (r() < 0.35 ? 'late' : r() < 0.15 ? 'forced' : 'early') : pick(r, ['early', 'early', 'late']);
    x.pos = pick(r, ['edge', 'center']);
  });
}
for (const x of m) if (x.t === TEAMS[0]) {
  const nf = 1 + Math.floor(r() * 3);
  for (let i = 0; i < nf; i++) {
    const phase = 1 + Math.floor(r() * Math.max(1, x.died || 6));
    const init = pick(r, ['us', 'us', 'them', 'third']);
    const tp = r() < 0.25 ? 1 : 0;
    const kf = Math.floor(r() * 4), ka = Math.floor(r() * 3) + tp;
    const fin = Math.min(kf, Math.round(kf * (0.4 + r() * 0.3)));
    const deaths = Math.min(4, Math.max(0, ka - Math.floor(r() * 2)));
    f.push([x.id, x.t, 120 + phase * 280 + Math.floor(r() * 200), phase, init, r() < 0.15 ? 1 : 0, kf, ka, fin, deaths, tp, 'SYNTHETIC']);
  }
}
const head = '# SYNTHETIC DEMO DATA generated by tools/gen_pubgm_demo.mjs (seed 2026). Not real matches.\n';
writeFileSync(new URL('../data/pubgm/demo_matches.csv', import.meta.url), head + 'match_id,date,session,event,map,lobby_strength,team,placement,elims,elims_early,elims_mid,elims_late,survival_s,drop_spot,drop_contested,vehicle_by_3min,died_phase,zone_entry,position,strategy\n' +
  m.map((x) => [x.id, `2026-11-0${3 + x.day}`, `D${x.day}`, 'SYNTHETIC scrims', x.map, x.lobby, x.t, x.placement, x.elims, x.e1, x.e2, x.e3, x.surv, x.drop, x.contested, x.vehicle, x.died, x.entry, x.pos, x.strat].join(',')).join('\n') + '\n');
writeFileSync(new URL('../data/pubgm/demo_fights.csv', import.meta.url), head + 'match_id,team,t_s,phase,initiator,zone_forced,knocks_for,knocks_against,finishes_for,team_deaths,third_party,notes\n' + f.map((x) => x.join(',')).join('\n') + '\n');
console.log(`wrote ${m.length} match rows, ${f.length} fight rows`);
